test("teacher submission requires a clean saved reconciled draft and locks saves/sources during preparation and confirmation", async () => {
  const f = fixture();
  await f.store.prepareSubmission();
  assert.equal(f.calls.length, 0);
  await f.drafts.view(lessonId);
  f.drafts.field({ ...content, title: "Unsaved" });
  await f.store.prepareSubmission();
  assert.equal(f.calls.length, 0);
  await f.drafts.save();
  await f.store.prepareSubmission();
  assert.equal(f.store.getSnapshot().confirmation.version, 5);
  assert.equal(f.drafts.getSnapshot().workflowLocked, true);
  await f.drafts.save(); await f.drafts.source(otherId, "remove");
  assert.equal(f.calls.filter(([kind]) => kind === "save").length, 1);
  assert.equal(f.calls.some(([kind]) => kind === "source"), false);
  f.store.cancelConfirmation();
  assert.equal(f.drafts.getSnapshot().workflowLocked, false);
});
test("duplicate submit confirmations send one version-checked write and retire only the confirmed editable draft", async () => {
  const f = fixture(); await f.drafts.view(lessonId); await f.store.prepareSubmission();
  const gate = deferred(), original = f.api.submit;
  f.api.submit = async (...args) => { const result = await original(...args); await gate.promise; return result; };
  const pending = f.store.confirm(); await f.store.confirm(); await f.drafts.save();
  assert.equal(f.calls.filter(([kind]) => kind === "submit").length, 1);
  assert.equal(f.store.getSnapshot().pending, "write");
  gate.resolve(); await pending;
  assert.equal(f.drafts.getSnapshot().form, null);
  assert.equal(f.store.getSnapshot().selected.revision.id, revisionId);
  assert.equal(f.store.getSnapshot().selected.workflow.state, "SUBMITTED");
  assert.equal(f.drafts.getSnapshot().workflowLocked, false);
});
for (const reason of ["rejected", "conflict", "unavailable", "invalid-response"]) test(`submission ${reason} preserves saved work and never adopts workflow versions`, async () => {
  const f = fixture(); await f.drafts.view(lessonId); await f.store.prepareSubmission();
  const before = structuredClone(f.drafts.getSnapshot().saved);
  f.api.submit = async () => { f.calls.push(["submit"]); throw new AuthApiError(reason, "Safe failure"); };
  await f.store.confirm();
  assert.deepEqual(f.drafts.getSnapshot().saved, before);
  assert.equal(f.drafts.getSnapshot().baseVersion, 4);
  if (reason === "conflict") { assert.equal(f.drafts.getSnapshot().blocked, true); f.store.clearSubmissionConflict(); assert.equal(f.drafts.getSnapshot().blocked, true); }
  if (["unavailable", "invalid-response"].includes(reason)) { assert.ok(f.store.getSnapshot().uncertain); await f.store.prepareSubmission(); }
  assert.equal(f.calls.filter(([kind]) => kind === "submit").length, 1);
});
test("lost submission recovery matches the baseline revision after later review/resubmission and keeps historical snapshots", async () => {
  const f = fixture(); await f.drafts.view(lessonId); await f.store.prepareSubmission();
  const original = f.api.submit;
  f.api.submit = async (...args) => { await original(...args); throw new AuthApiError("unavailable", "Lost response"); };
  await f.store.confirm();
  const first = structuredClone(f.revisions[0]);
  first.review = { ...review, decision: "REQUEST_CHANGES", feedback: "Explain halves." };
  f.revisions = [first, { ...structuredClone(first), id: otherId, number: 2, content: { ...content, title: "Later draft text" }, sources: [{ ...first.sources[0], resourceVersion: 2, snapshot: { ...first.sources[0].snapshot, contentText: "Later resource text" } }], review: null }];
  f.current = { lessonId, version: 9, state: "SUBMITTED", currentRevisionId: otherId };
  await f.store.recover();
  assert.equal(f.store.getSnapshot().uncertain.kind, "submit");
  assert.equal(f.store.getSnapshot().recovered, true);
  assert.deepEqual(f.store.getSnapshot().selected.revision.sources, first.sources);
  assert.equal(f.store.getSnapshot().selected.revision.review.feedback, "Explain halves.");
  assert.equal(f.store.getSnapshot().selected.workflow.currentRevisionId, otherId);
  assert.equal(f.drafts.getSnapshot().baseVersion, 4);
  f.store.acknowledgeRecovery();
  assert.equal(f.store.getSnapshot().uncertain, null);
  assert.equal(f.drafts.getSnapshot().form, null);
  assert.equal(f.calls.filter(([kind]) => kind === "submit").length, 1);
});
test("absent/different results and failed reconciliation cannot release submission uncertainty", async () => {
  const f = fixture(); await f.drafts.view(lessonId); await f.store.prepareSubmission();
  f.api.submit = async () => { throw new AuthApiError("unavailable", "Lost"); };
  await f.store.confirm(); await f.store.recover(); f.store.acknowledgeRecovery();
  assert.ok(f.store.getSnapshot().uncertain);
  assert.equal(f.store.getSnapshot().recovered, false);
  f.revisions = [{ ...structuredClone(submitted.revision), content: { ...content, title: "Different winner" } }];
  f.current = structuredClone(submitted.workflow);
  await f.store.recover(); f.store.acknowledgeRecovery();
  assert.ok(f.store.getSnapshot().uncertain);
  f.revisions[0].content = structuredClone(content);
  await f.store.recover(); assert.equal(f.store.getSnapshot().recovered, true);
  f.api.history = async () => { throw new AuthApiError("unavailable", "Read failed"); };
  await f.store.recover(); f.store.acknowledgeRecovery();
  assert.equal(f.store.getSnapshot().recovered, false);
  assert.ok(f.store.getSnapshot().uncertain);
  assert.equal(f.drafts.getSnapshot().workflowLocked, true);
});
