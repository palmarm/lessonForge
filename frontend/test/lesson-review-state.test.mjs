test("pause invalidates old read successes/401s and pending writes become uncertain; disposal rejects later results", async () => {
  const f = fixture("ADMIN"), read = deferred();
  f.api.detail = () => read.promise;
  const pending = f.store.detail(lessonId, revisionId); f.store.pause(true); f.store.pause(false);
  read.reject(new AuthApiError("unauthenticated", "Old 401")); await pending;
  assert.equal(f.ended, 0); assert.equal(f.store.getSnapshot().selected, null);
  f.api.detail = async () => structuredClone(submitted); await f.store.detail(lessonId, revisionId);
  f.store.comments("Retain through pause"); f.store.prepareReview("APPROVE");
  const write = deferred(); f.api.review = () => write.promise;
  const writing = f.store.confirm(); f.store.pause(true);
  assert.equal(f.store.getSnapshot().uncertain.kind, "review");
  assert.equal(f.store.getSnapshot().comments, "Retain through pause");
  f.store.dispose(); f.store.activate(); write.resolve({ ...submitted, revision: { ...submitted.revision, review } }); await writing;
  assert.deepEqual(f.store.getSnapshot(), initialReviewState);
});
test("navigation protects dirty review comments separately from pending/uncertain writes", async () => {
  const f = fixture("ADMIN"), navigation = createWorkspaceNavigation();
  navigation.register(() => { const s = f.store.getSnapshot(); return { dirty: !!s.comments, blocked: s.pending === "write" || !!s.uncertain, paused: false }; });
  f.store.comments("Dirty comments"); assert.equal(navigation.allow(() => false), false);
  assert.equal(navigation.allow(() => true), true);
  f.api.detail = async () => structuredClone(submitted); await f.store.detail(lessonId, revisionId, true);
  f.store.prepareReview("APPROVE"); f.api.review = async () => { throw new AuthApiError("unavailable", "Lost"); }; await f.store.confirm();
  assert.equal(navigation.allow(() => true), false);
});
